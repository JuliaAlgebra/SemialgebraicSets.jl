export truncated

"""
    struct TruncatedIdeal{T,PT<:MP.AbstractPolynomialLike{T}}
        generators::Vector{PT}
        maxdegree::Int
    end

Truncation at degree `maxdegree` of the ideal generated by `generators`
`h_1, ..., h_m`, i.e., the vector space of polynomials
`λ_1 * h_1 + ... + λ_m * h_m` where `λ_1, ..., λ_m` are polynomials such that
the degree of `λ_i * h_i` is at most `maxdegree` for all `i`. Equivalently, it
is the row space of the Macaulay matrix of degree `maxdegree` of the
generators.

It is a subspace of the polynomials of degree at most `maxdegree` of the
ideal generated by the generators but it may be strictly smaller if a
combination of the generators has a degree smaller than the degree of the
generators that are combined (a degree fall). In particular, unlike the ideal,
it depends on the choice of generators. As `maxdegree` grows, it eventually
contains all the polynomials of degree at most a given degree of the ideal.
"""
struct TruncatedIdeal{T,PT<:_APL{T}}
    generators::Vector{PT}
    maxdegree::Int
end

MP.coefficient_type(::Type{<:TruncatedIdeal{T}}) where {T} = T

"""
    truncated(I::PolynomialIdeal, maxdegree::Integer)

Return the [`TruncatedIdeal`](@ref) of the generators of `I` at degree
`maxdegree`.
"""
function truncated(I::PolynomialIdeal{T,PT}, maxdegree::Integer) where {T,PT}
    return TruncatedIdeal{T,PT}(I.p, maxdegree)
end

"""
    struct TruncatedAlgebraicSet{T,V<:AlgebraicSet{T}} <: AbstractAlgebraicSet
        set::V
        maxdegree::Int
    end

Algebraic set with the same points as `set` but whose [`ideal`](@ref) is the
[`TruncatedIdeal`](@ref) of the equalities of `set` at degree `maxdegree`.
"""
struct TruncatedAlgebraicSet{T,V<:AlgebraicSet{T}} <: AbstractAlgebraicSet
    set::V
    maxdegree::Int
end

"""
    truncated(V::AlgebraicSet, maxdegree::Integer)

Return the [`TruncatedAlgebraicSet`](@ref) of `V` at degree `maxdegree`. Its
points are the points of `V` but its [`ideal`](@ref) is the
[`TruncatedIdeal`](@ref) of the equalities of `V` at degree `maxdegree`.
Therefore, a polynomial is certified to vanish on it if it is a combination
`λ_1 * h_1 + ... + λ_m * h_m` of the equalities `h_1, ..., h_m` of `V`
where the degree of `λ_i * h_i` is at most `maxdegree`.

## Example

The polynomial `x - y` vanishes on `V = @set x * y == 1 && y^2 == 1` as
`x - y = y * (x * y - 1) - x * (y^2 - 1)`. It belongs to the ideal of
`truncated(V, 3)` but not to the ideal of `truncated(V, 2)`.
"""
function truncated(V::AlgebraicSet{T}, maxdegree::Integer) where {T}
    return TruncatedAlgebraicSet{T,typeof(V)}(V, maxdegree)
end

ideal(V::TruncatedAlgebraicSet) = truncated(ideal(V.set), V.maxdegree)

MP.coefficient_type(::Type{<:TruncatedAlgebraicSet{T}}) where {T} = T
function MP.similar_type(
    ::Type{TruncatedAlgebraicSet{U,V}},
    T::Type,
) where {U,V}
    return TruncatedAlgebraicSet{T,MP.similar_type(V, T)}
end
function Base.convert(
    ::Type{TruncatedAlgebraicSet{T,V}},
    set::TruncatedAlgebraicSet{T,V},
) where {T,V<:AlgebraicSet{T}}
    return set
end
function Base.convert(
    ::Type{TruncatedAlgebraicSet{T,V}},
    set::TruncatedAlgebraicSet,
) where {T,V}
    return TruncatedAlgebraicSet{T,V}(convert(V, set.set), set.maxdegree)
end

MP.variables(V::TruncatedAlgebraicSet) = MP.variables(V.set)

function SA.promote_with_map(V::TruncatedAlgebraicSet, new_vars, exponent_map)
    new_set, _ = SA.promote_with_map(V.set, new_vars, exponent_map)
    return truncated(new_set, V.maxdegree), exponent_map
end

function _needs_promotion(V::TruncatedAlgebraicSet, vars)
    return _needs_promotion(V.set, vars)
end
function MP.monomial_type(::Type{<:TruncatedAlgebraicSet{T,V}}) where {T,V}
    return MP.monomial_type(V)
end
nequalities(V::TruncatedAlgebraicSet) = nequalities(V.set)
equalities(V::TruncatedAlgebraicSet) = equalities(V.set)

function Base.show(io::IO, V::TruncatedAlgebraicSet)
    print(io, "truncated(")
    show(io, V.set)
    return print(io, ", ", V.maxdegree, ")")
end
function Base.show(io::IO, mime::MIME"text/plain", V::TruncatedAlgebraicSet)
    print(io, "Algebraic Set truncated at degree $(V.maxdegree) defined by ")
    return _show_els(io, "equalit", nequalities(V), equalities(V), "=")
end
